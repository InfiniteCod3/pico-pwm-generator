static i2c_inst_t *port;
static uint8_t addr;
static uint8_t fb[OLED_WIDTH * OLED_HEIGHT / 8];

static bool send(const uint8_t *data, size_t len) {
    return i2c_write_timeout_us(port, addr, data, len, false, 20000) == (int)len;
}

static bool command(uint8_t cmd) {
    uint8_t buf[2] = {0x00, cmd};
    return send(buf, 2);
}

bool oled_init(i2c_inst_t *i2c, uint sda_pin, uint scl_pin) {
    i2c_init(i2c, 400000);
    gpio_pull_up(sda_pin);
    gpio_pull_up(scl_pin);
    gpio_set_function(sda_pin, GPIO_FUNC_I2C);
    gpio_set_function(scl_pin, GPIO_FUNC_I2C);
    sleep_ms(200);

    port = i2c;
    addr = 0x3C;
    if (!command(0xAE)) addr = 0x3D;

    static const uint8_t init[] = {
        0xAE, 0xD5, 0x80, 0xA8, 0x1F, 0xD3, 0x00, 0x40, 0x8D, 0x14, 0x20, 0x00, 0xA1,
        0xC8, 0xDA, 0x02, 0x81, 0xCF, 0xD9, 0xF1, 0xDB, 0x40, 0xA4, 0xA6, 0xAF,
    };
    for (size_t i = 0; i < sizeof(init); i++) {
        if (!command(init[i])) return false;
    }

    oled_clear();
    oled_show();
    return true;
}

void oled_clear(void) {
    memset(fb, 0, sizeof(fb));
}

static void pixel(int x, int y, bool invert) {
    if (x < 0 || y < 0 || x >= OLED_WIDTH || y >= OLED_HEIGHT) return;
    uint8_t bit = 1 << (y % 8);
    uint8_t *p = &fb[y / 8 * OLED_WIDTH + x];
    if (invert) *p ^= bit;
    else *p |= bit;
}

void oled_char(int x, int y, char c, int scale) {
    for (int col = 0; col < 5; col++) {
        for (int row = 0; row < 8; row++) {
            if (!(font[c - ' '][col] & (1 << row))) continue;
            for (int dy = 0; dy < scale; dy++) {
                for (int dx = 0; dx < scale; dx++) pixel(x + col * scale + dx, y + row * scale + dy, false);
            }
        }
    }
}

void oled_text(int x, int y, const char *s, int scale) {
    for (; *s; s++, x += OLED_CHAR_WIDTH * scale) oled_char(x, y, *s, scale);
}

void oled_invert(int x, int y, int w, int h) {
    for (int yy = y; yy < y + h; yy++) {
        for (int xx = x; xx < x + w; xx++) pixel(xx, yy, true);
    }
}

void oled_show(void) {
    static uint8_t buf[1 + OLED_WIDTH] = {0x40};
    for (int page = 0; page < OLED_HEIGHT / 8; page++) {
        if (!command(0xB0 + page) || !command(0x00) || !command(0x10)) return;
        memcpy(buf + 1, fb + page * OLED_WIDTH, OLED_WIDTH);
        send(buf, sizeof(buf));
    }
}
